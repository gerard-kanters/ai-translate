/**
 * Return the WordPress sub-directory path for subfolder installs (e.g. '/moretti').
 * Returns an empty string when WordPress is installed at the domain root.
 * Result is cached statically; safe to call many times per request.
 *
 * @return string  Sub-directory prefix without trailing slash, e.g. '/moretti' or ''.
 */
function ai_translate_site_path(): string
{
    static $p = null;
    if ($p === null) {
        // Use get_option('home') directly to bypass any home_url filters (e.g. the language-prefix
        // filter registered by this plugin), so we always get the real installation path.
        $raw = trailingslashit((string) get_option('home', get_option('siteurl', '')));
        $p   = rtrim((string) wp_parse_url($raw, PHP_URL_PATH), '/');
    }
    return $p;
}

/**
 * Strip the WordPress sub-directory prefix from a URL path derived from REQUEST_URI.
 * On root installs the path is returned unchanged (ai_translate_site_path() === '').
 *
 * @param string $path  Full request path, e.g. '/moretti/en/contact/'.
 * @return string       Site-relative path, e.g. '/en/contact/'.
 */
function ai_translate_strip_site_path(string $path): string
{
    $sub = ai_translate_site_path();
    if ($sub === '') {
        return $path;
    }
    if (str_starts_with($path, $sub . '/')) {
        return substr($path, strlen($sub)) ?: '/';
    }
    if ($path === $sub) {
        return '/';
    }
    return $path;
}

/**
 * Subfolder support: prepend the WordPress sub-directory to bare redirect paths
 * generated by AI Translate (e.g. '/' → '/moretti/', '/en/' → '/moretti/en/').
 * No-op on root installations where ai_translate_site_path() returns ''.
 */
add_filter('wp_redirect', function (string $location): string {
    $sub = ai_translate_site_path();
    if ($sub === '') {
        return $location;
    }
    // Leave absolute URLs and paths already starting with the sub-directory alone.
    if (strpos($location, '://') !== false) {
        return $location;
    }
    if (str_starts_with($location, $sub . '/') || $location === $sub) {
        return $location;
    }
    // Only intercept root or language-prefixed paths to avoid interfering with other plugins.
    if ($location === '/' || preg_match('#^/[a-z]{2}(?:/|$)#i', $location)) {
        return $sub . $location;
    }
    return $location;
}, 5);

/**
 * Load the plugin text domain with locale fallback chain.
 *
 * @param bool $force_user_locale When true, forces the logged-in user's locale instead of the site locale.
 * @return void
 */
function ai_translate_load_textdomain($force_user_locale = false)
{
    // If forced to use user locale (for admin)
    if ($force_user_locale && is_user_logged_in()) {
        $locale = get_user_locale();
    } else {
        $locale = get_locale();
    }

    $plugin_dir = plugin_dir_path(__FILE__);
    $lang_dir = $plugin_dir . 'languages/';

    // Build fallback chain: exact -> base -> language code
    $fallback_locales = array($locale);
    
    // If locale has underscores, extract base locale (e.g., nl_NL_formal -> nl_NL)
    if (strpos($locale, '_') !== false) {
        $parts = explode('_', $locale);
        if (count($parts) >= 2) {
            $base_locale = $parts[0] . '_' . $parts[1];
            if (!in_array($base_locale, $fallback_locales, true)) {
                $fallback_locales[] = $base_locale;
            }
        }
        // Also try language code only (e.g., nl_NL -> nl)
        if (count($parts) >= 1) {
            $lang_only = $parts[0];
            if (!in_array($lang_only, $fallback_locales, true)) {
                $fallback_locales[] = $lang_only;
            }
        }
    }
    
    // Try each locale in fallback chain
    foreach ($fallback_locales as $try_locale) {
        $mofile = $lang_dir . 'ai-translate-' . $try_locale . '.mo';
        if (file_exists($mofile)) {
            // Unload existing textdomain first if reloading
            if ($force_user_locale && is_textdomain_loaded('ai-translate')) {
                unload_textdomain('ai-translate');
            }
            load_textdomain('ai-translate', $mofile);
            if (is_textdomain_loaded('ai-translate')) {
                return;
            }
        }
    }
    
    // Final fallback to standard load_plugin_textdomain. Plugin ships its own .mo files in
    // /languages/, so we cannot rely solely on WordPress 4.6+ automatic translation loading
    // (which only picks up /wp-content/languages/plugins/ai-translate-*.mo files).
    // phpcs:ignore PluginCheck.CodeAnalysis.DiscouragedFunctions.load_plugin_textdomainFound -- needed for bundled translations
    load_plugin_textdomain(
        'ai-translate',
        false,
        dirname(plugin_basename(__FILE__)) . '/languages/'
    );
}

