/**
 * Map ai_path to WordPress internal query vars.
 */
add_filter('request', function ($vars) {
    // Hard skip for admin paths
    $req = isset($_SERVER['REQUEST_URI']) ? esc_url_raw(wp_unslash((string) $_SERVER['REQUEST_URI'])) : '';
    if ($req !== '' && (strpos($req, '/wp-admin/') !== false || strpos($req, 'wp-login.php') !== false)) {
        return $vars;
    }
    // Fallback: if rewrite did not set ai_translate_path (e.g. URL with %), extract path from REQUEST_URI
    if (empty($vars['ai_translate_path']) && !empty($req) && preg_match('#^/([a-z]{2})/([^?]+)#i', $req, $m)) {
        $path_from_uri = ai_translate_strip_site_path((string) wp_parse_url($req, PHP_URL_PATH));
        if ($path_from_uri !== '' && preg_match('#^/([a-z]{2})(?:/(.*))?$#i', $path_from_uri, $path_m)) {
            $vars['lang'] = strtolower($path_m[1]);
            $vars['ai_translate_path'] = isset($path_m[2]) ? trim($path_m[2], '/') : '';
        }
    }
    // ai_translate_path: the generic rewrite rule sets ai_translate_path for /{lang}/{path}/.
    // Resolve to post before the main query so the correct page_id or p+post_type is included.
    if (!empty($vars['ai_translate_path']) && !empty($vars['lang'])) {
        $path = trim((string) $vars['ai_translate_path'], '/');
        $lang = (string) $vars['lang'];
        // Split off a rewrite-endpoint or /page/N suffix (e.g. 'my-account/orders',
        // 'shop/page/2') so the base path can be resolved via the slug map.
        $suffix_info = ai_translate_split_endpoint_suffix($path);
        $resolve_path = ($suffix_info['suffix'] !== '' && $suffix_info['base'] !== '') ? $suffix_info['base'] : $path;
        $post_id = \AITranslate\AI_Slugs::resolve_path_to_post($lang, $resolve_path);
        if (!$post_id && strpos($resolve_path, '/') !== false) {
            $base = basename($resolve_path);
            $post_id = \AITranslate\AI_Slugs::resolve_path_to_post($lang, $base);
            if (!$post_id) {
                // Generic fallback: try to find post by translated slug (prefers non-attachments)
                $post_id = \AITranslate\AI_Slugs::resolve_translated_slug_to_post($base, $lang);
            }
        }
        if ($post_id) {
            $post = get_post($post_id);
            if ($post && $post->post_status === 'publish') {
                if ($post->post_type === 'page') {
                    $vars['page_id'] = (int) $post->ID;
                } else {
                    $vars['p'] = (int) $post->ID;
                    $vars['post_type'] = $post->post_type;
                }
                if ($suffix_info['endpoint'] !== null) {
                    $vars[$suffix_info['endpoint']] = $suffix_info['value'];
                } elseif ($suffix_info['paged'] > 1) {
                    $vars['paged'] = $suffix_info['paged'];
                }
            }
            unset($vars['ai_translate_path']);
        } else {
            // Path did not resolve to a post; try taxonomy (category, tag, custom tax).
            $resolved_term = ai_translate_resolve_term_from_path($path);
            if ($resolved_term) {
                $vars = ai_translate_apply_resolved_term_to_vars($vars, $resolved_term);
                unset($vars['ai_translate_path']);
            }
        }
    }
    // Handle 'lang' query var: map translated slug back to source for both pages and singles
    if (isset($vars['lang'])) {
        // pagename can be hierarchical: map EACH segment back to its source slug
        if (!empty($vars['pagename'])) {
            $pg = (string) $vars['pagename'];
            $segments = array_values(array_filter(explode('/', trim($pg, '/'))));
            if (!empty($segments)) {
                foreach ($segments as $i => $seg) {
                    $src = \AITranslate\AI_Slugs::resolve_any_to_source_slug((string) $seg);
                    if ($src) {
                        $segments[$i] = $src;
                    }
                }
                $vars['pagename'] = implode('/', $segments);
            }
        }
        if (!empty($vars['name'])) {
            $nm = (string) $vars['name'];
            // If post_type is specified, use it to resolve slug conflicts
            $expected_post_type = !empty($vars['post_type']) ? $vars['post_type'] : null;
            $src = \AITranslate\AI_Slugs::resolve_any_to_source_slug($nm, $expected_post_type);
            if (!$src && !empty($vars['lang'])) {
                // Generic fallback: find post by translated slug with post_type filter
                if ($expected_post_type) {
                    $post_id = \AITranslate\AI_Slugs::resolve_translated_slug_to_post_by_type($nm, (string) $vars['lang'], $expected_post_type);
                } else {
                    $post_id = \AITranslate\AI_Slugs::resolve_translated_slug_to_post($nm, (string) $vars['lang']);
                }
                if ($post_id) {
                    $post = get_post($post_id);
                    if ($post && $post->post_status === 'publish') {
                        $src = $post->post_name;
                    }
                }
            }
            if ($src) {
                $vars['name'] = $src;
            }
        }
    }
    return $vars;
});

/**
 * Detect page-builder editor / preview context (Elementor, Divi, Beaver, WPBakery, Oxygen,
 * Bricks, Breakdance, Brizy, Thrive) and WordPress core post preview.
 *
 * Editor previews are loaded inside an iframe by a logged-in admin and depend on the
 * original (untranslated) URL plus query parameters. The plugin must NOT redirect or
 * translate these requests, otherwise the editor loses preview parameters and the
 * builder reports a session error.
 *
 * @return bool True when the current request is a builder/preview context.
 */
function ai_translate_is_editor_context()
{
    // phpcs:disable WordPress.Security.NonceVerification.Recommended -- read-only detection only.
    static $is_editor = null;
    if ($is_editor !== null) {
        return $is_editor;
    }

    // Known, builder-specific query parameters (verified in each builder's source).
    $builder_params = array(
        'elementor-preview',         // Elementor editor preview iframe
        'elementor_library',         // Elementor library preview
        'et_fb',                     // Divi Visual Builder
        'et_pb_preview',             // Divi preview
        'fl_builder',                // Beaver Builder
        'vc_editable',               // WPBakery / Visual Composer
        'vc_action',                 // WPBakery / Visual Composer
        'tve',                       // Thrive Architect
        'ct_builder',                // Oxygen Builder
        'oxygen',                    // Oxygen Builder loader URL
        'bricks',                    // Bricks Builder
        'breakdance',                // Breakdance Builder loader URL (?breakdance=builder)
        'breakdance_iframe',         // Breakdance Builder iframe
        'breakdance_open_document',  // Breakdance render document
        '_breakdance_doing_ajax',    // Breakdance frontend AJAX (POST /?page_id=X&_breakdance_doing_ajax=yes)
        'brizy-edit',                // Brizy Builder
        'brizy-edit-iframe',         // Brizy Builder iframe
        'uxb_iframe',                // Flatsome UX Builder iframe (?post_id=X&uxb_iframe=1)
        'td_action',                 // Newspaper tagDiv Composer edit mode (?td_action=tdc)
        'tdc_action',                // Newspaper tagDiv Composer iframe (?tdc_action=iframe)
        'fb-edit',                   // Avada Live frontend builder (?fb-edit=1)
    );
    foreach ($builder_params as $param) {
        if (isset($_GET[$param])) {
            $is_editor = true;
            return true;
        }
    }

    // WordPress core post preview (preview=true and/or preview_id) — only for users
    // that can actually edit, to avoid abuse via crafted query strings on public URLs.
    $has_preview_param = (
        (isset($_GET['preview']) && (string) $_GET['preview'] !== 'false')
        || isset($_GET['preview_id'])
        || isset($_GET['preview_nonce'])
    );
    if ($has_preview_param && is_user_logged_in()) {
        $is_editor = true;
        return true;
    }

    // Generic fallback: any iframe loaded from /wp-admin/ by a user with edit capability.
    // Sec-Fetch-Dest is sent by all modern browsers (Chrome 80+, Firefox 90+, Safari 16.4+).
    // Combination of iframe destination + wp-admin Referer + edit capability uniquely
    // identifies a builder preview iframe, so unknown/future builders are also covered
    // without us needing to learn each builder's specific query parameter.
    if (is_user_logged_in() && function_exists('current_user_can') && current_user_can('edit_posts')) {
        $sec_fetch_dest = isset($_SERVER['HTTP_SEC_FETCH_DEST'])
            ? sanitize_text_field(wp_unslash((string) $_SERVER['HTTP_SEC_FETCH_DEST']))
            : '';
        if ($sec_fetch_dest === 'iframe' || $sec_fetch_dest === 'frame') {
            $referer = wp_get_referer();
            if ($referer && strpos((string) $referer, '/wp-admin/') !== false) {
                $is_editor = true;
                return true;
            }
        }
    }

    $is_editor = false;
    return false;
    // phpcs:enable WordPress.Security.NonceVerification.Recommended
}

/**
 * Check if current request is an XML file (sitemap, robots.txt, etc.).
 *
 * @return bool
 */
function ai_translate_is_xml_request()
{
    $reqPathRaw = esc_url_raw(wp_unslash((string) ($_SERVER['REQUEST_URI'] ?? '')));
    // URL decode only if double-encoded (contains %25 indicating double encoding)
    if (strpos($reqPathRaw, '%25') !== false) {
        $reqPathRaw = urldecode($reqPathRaw);
    }
    $reqPath = ai_translate_strip_site_path((string) wp_parse_url($reqPathRaw, PHP_URL_PATH));

    // Check if path ends with .xml
    if (preg_match('/\.xml$/i', $reqPath)) {
        return true;
    }

    // Check for WordPress sitemap query vars
    if (isset($_GET['sitemap']) || isset($_GET['sitemap-index'])) {
        return true;
    }

    // Check for sitemap in path (e.g., /wp-sitemap.xml, /sitemap.xml)
    if (preg_match('/sitemap/i', $reqPath)) {
        return true;
    }

    return false;
}

/**
 * Check if the current request's User-Agent is a known search engine crawler.
 * Used to keep bots on the default language instead of following browser-language
 * auto-detection (crawlers rarely send a meaningful Accept-Language header, and
 * should never trigger/see a language redirect for SEO consistency).
 *
 * @return bool
 */
function ai_translate_is_known_bot_ua()
{
    $ua = isset($_SERVER['HTTP_USER_AGENT']) ? sanitize_text_field(wp_unslash((string) $_SERVER['HTTP_USER_AGENT'])) : '';
    return $ua !== '' && (bool) preg_match('/googlebot|googleother|bingbot|yandexbot|baiduspider|duckduckbot|slurp|facebot|ia_archiver/i', $ua);
}

/**
 * Whether a URL (Referer/Origin) belongs to this site.
 * Compares host (and subdirectory path when applicable). Rejects prefix tricks
 * like https://example.com.attacker.tld/ that pass a naive strpos(home_url()) check.
 *
 * @param string $url Absolute URL or Origin header value.
 * @return bool
 */
function ai_translate_is_same_site_url($url)
{
    $url = esc_url_raw(trim((string) $url));
    if ($url === '') {
        return false;
    }

    $home_parts = wp_parse_url(home_url('/'));
    $url_parts = wp_parse_url($url);
    if (!is_array($home_parts) || !is_array($url_parts)) {
        return false;
    }

    $home_host = isset($home_parts['host']) ? strtolower((string) $home_parts['host']) : '';
    $url_host = isset($url_parts['host']) ? strtolower((string) $url_parts['host']) : '';
    if ($home_host === '' || $url_host === '' || $home_host !== $url_host) {
        return false;
    }

    $home_scheme = isset($home_parts['scheme']) ? strtolower((string) $home_parts['scheme']) : 'http';
    $url_scheme = isset($url_parts['scheme']) ? strtolower((string) $url_parts['scheme']) : '';
    // Origin headers always include a scheme; Referer should too. Only http/https allowed.
    if ($url_scheme === '' || !in_array($url_scheme, ['http', 'https'], true) || !in_array($home_scheme, ['http', 'https'], true)) {
        return false;
    }

    $home_port = isset($home_parts['port']) ? (int) $home_parts['port'] : null;
    $url_port = isset($url_parts['port']) ? (int) $url_parts['port'] : null;
    if ($home_port !== $url_port) {
        return false;
    }

    // Subdirectory installs: URL path must stay under the site path.
    $home_path = isset($home_parts['path']) ? untrailingslashit((string) $home_parts['path']) : '';
    if ($home_path !== '' && $home_path !== '/') {
        $url_path = isset($url_parts['path']) ? (string) $url_parts['path'] : '/';
        if ($url_path !== $home_path && strpos($url_path, $home_path . '/') !== 0) {
            return false;
        }
    }

    return true;
}

/**
 * Add Accept-Language/Cookie to the Vary header on language-detection-based redirects.
 *
 * These redirects (browser-language auto-detect, cookie-based root/path redirects) decide
 * their target based on request headers, not just the URL. A shared cache (CDN/reverse proxy)
 * that does not honor Cache-Control but does honor Vary will otherwise reuse one visitor's
 * redirect for every other visitor of the same URL. This is defense-in-depth alongside the
 * existing nocache_headers() call, not a replacement for it.
 *
 * @return void
 */
function ai_translate_add_vary_headers()
{
    if (headers_sent()) {
        return;
    }
    $existing = [];
    foreach (headers_list() as $h) {
        if (stripos($h, 'Vary:') === 0) {
            $existing = array_map('trim', explode(',', substr($h, strlen('Vary:'))));
            break;
        }
    }
    $merged = array_values(array_unique(array_filter(array_merge($existing, ['Accept-Language', 'Cookie']))));
    header('Vary: ' . implode(', ', $merged));
}

/**
 * Start output buffering for front-end (skip admin, AJAX, REST, feeds and XML files).
 * Handles language detection and redirection according to the 4 language switcher rules.
 */
// Check for _wp_old_slug redirects before other plugin logic (priority 1).
// Request path is checked first: if it matches an old slug in DB, redirect. Do not rely on is_404
// because themes/plugins may serve the homepage instead of 404 for unknown slugs.
add_action('template_redirect', function () {
    if (!isset($_SERVER['REQUEST_URI'])) {
        return;
    }
    $request_uri = esc_url_raw(wp_unslash((string) $_SERVER['REQUEST_URI']));
    $request_path = ai_translate_strip_site_path((string) wp_parse_url($request_uri, PHP_URL_PATH));
    if (!is_string($request_path) || $request_path === '' || $request_path === '/') {
        return;
    }
    // Skip if URL has language prefix (let AI Translate handle those)
    if (preg_match('#^/([a-z]{2})(?:/|$)#i', $request_path)) {
        return;
    }
    // Single-segment path (e.g. /programmeren-met-een-ai-agen/) – might be an old slug
    $path_parts = array_filter(explode('/', trim($request_path, '/')));
    if (empty($path_parts)) {
        return;
    }
    $slug = end($path_parts);
    global $wpdb;
    $post_id = $wpdb->get_var($wpdb->prepare(
        "SELECT post_id FROM {$wpdb->postmeta} WHERE meta_key = '_wp_old_slug' AND meta_value = %s LIMIT 1",
        $slug
    ));
    if (!$post_id) {
        return;
    }
    $post = get_post($post_id);
    if (!$post || $post->post_status !== 'publish') {
        return;
    }
    $permalink = get_permalink($post);
    if ($permalink) {
        wp_safe_redirect($permalink, 301);
        exit;
    }
}, 1);

/**
 * Conservative 404 recovery: when a request would otherwise serve a 404, look
 * up the basename in the slug map (any language) and redirect to the canonical
 * translated URL when there is exactly one safe match. Only acts on
 * /{lang}/... paths and never triggers a new translation. See
 * docs/404-herstelplan-op-basis-van-url.md (Fase 1).
 *
 * Runs at priority 999 so it executes after all other template_redirect
 * callbacks have had a chance to resolve or fix the request.
 */
add_action('template_redirect', function () {
    if (!is_404()) {
        return;
    }
    if (is_admin() || wp_doing_ajax() || wp_is_json_request() || is_feed() || ai_translate_is_xml_request()) {
        return;
    }
    if (!isset($_SERVER['REQUEST_URI'])) {
        return;
    }
    $reqUriRaw = esc_url_raw(wp_unslash((string) $_SERVER['REQUEST_URI']));
    if (strpos($reqUriRaw, '%25') !== false) {
        $reqUriRaw = urldecode($reqUriRaw);
    }
    $request_path = ai_translate_strip_site_path((string) (wp_parse_url($reqUriRaw, PHP_URL_PATH) ?: '/'));

    $target_url = \AITranslate\AI_404_Recovery::resolve($request_path);
    if (!is_string($target_url) || $target_url === '') {
        return;
    }

    nocache_headers();
    wp_safe_redirect(esc_url_raw($target_url), 301);
    exit;
}, 999);

add_action('template_redirect', function () {
    // Handle ai_translate_path query var for custom URL resolution
    if (isset($_GET['ai_translate_path'])) {
        $path = sanitize_text_field(wp_unslash($_GET['ai_translate_path']));
        // Remove the query var so WordPress doesn't see it
        unset($_GET['ai_translate_path']);

        // Try to resolve the path without language prefix
        $resolved_post = \AITranslate\AI_Slugs::resolve_path_to_post('', $path);
        if ($resolved_post) {
            // Set the resolved post ID so WordPress loads the correct content
            global $wp_query;
            $wp_query->set('p', $resolved_post);
            $wp_query->set('post_type', 'any');
            // Make sure WordPress knows this is a singular post
            $wp_query->is_singular = true;
            $wp_query->is_single = true;
            $wp_query->is_archive = false;
            $wp_query->is_page = false;
        }
    }

    // Skip admin/AJAX/REST/feeds/XML files
    if (is_admin() || wp_doing_ajax() || wp_is_json_request() || is_feed() || ai_translate_is_xml_request()) {
        return;
    }

    // Skip page-builder editor/preview iframes (Elementor, Divi, Beaver, ...) and WP post preview.
    // These are loaded by a logged-in admin and rely on the original URL + query parameters.
    // Redirecting them to /{lang}/ would drop the preview parameters and break the editor
    // ("Session expired" in Elementor). The frontend is rendered as-is in the default language.
    if (ai_translate_is_editor_context()) {
        return;
    }

    $reqPathRaw = esc_url_raw(wp_unslash((string) ($_SERVER['REQUEST_URI'] ?? '')));
    // URL decode only if double-encoded (contains %25 indicating double encoding)
    if (strpos($reqPathRaw, '%25') !== false) {
        $reqPathRaw = urldecode($reqPathRaw);
    }
    $reqPath = ai_translate_strip_site_path((string) wp_parse_url($reqPathRaw, PHP_URL_PATH));
    $defaultLang = \AITranslate\AI_Lang::default();
    
    // CRITICAL: If we're on /{default}/ and cookie doesn't match, render page FIRST
    // This prevents redirect before cookie is set
    if ($reqPath !== '' && preg_match('#^/([a-z]{2})(?:/|$)#i', $reqPath, $m)) {
        $langFromUrl = strtolower(sanitize_key($m[1]));
        if ($defaultLang && strtolower($langFromUrl) === strtolower((string) $defaultLang)) {
            $cookieLang = isset($_COOKIE['ai_translate_lang']) ? strtolower(sanitize_key((string) $_COOKIE['ai_translate_lang'])) : '';
            // If cookie doesn't match, set language and render page (don't redirect yet)
            if ($cookieLang !== '' && strtolower($cookieLang) !== strtolower((string) $defaultLang)) {
                \AITranslate\AI_Lang::set_cookie((string) $defaultLang);
                \AITranslate\AI_Lang::set_current((string) $defaultLang);
                // Add JavaScript redirect to site root after page renders
                add_action('wp_footer', function() {
                    echo '<script>window.location.replace(' . wp_json_encode(home_url('/')) . ');</script>';
                }, 999);
                // Continue to render page - Rule 3 below will be skipped
                // Set final language and start OB
                $finalLang = (string) $defaultLang;
                \AITranslate\AI_Lang::set_current($finalLang);
                add_filter('locale', function ($locale) use ($finalLang) {
                    return strtolower($finalLang) . '_' . strtoupper($finalLang);
                });
                \AITranslate\AI_OB::instance()->start();
                return; // Stop here - don't execute Rule 3 redirect
            }
        }
    }

    // Check if we just switched languages - switcher has HIGHEST priority!

    // Extract language from URL
    $langFromUrl = null;
    if ($reqPath !== '' && preg_match('#^/([a-z]{2})(?:/|$)#i', $reqPath, $m)) {
        $langFromUrl = strtolower(sanitize_key($m[1]));
        
        // SECURITY: Prevent unauthorized translation by blocking non-enabled/non-detectable languages
        // If language is in URL but not enabled or detectable, return 404 to prevent API costs
        if ($langFromUrl !== null && $defaultLang && strtolower($langFromUrl) !== strtolower((string) $defaultLang)) {
            $enabled = \AITranslate\AI_Lang::enabled();
            $detectable = \AITranslate\AI_Lang::detectable();
            $langLower = strtolower($langFromUrl);
            $isEnabled = in_array($langLower, array_map('strtolower', $enabled), true);
            $isDetectable = in_array($langLower, array_map('strtolower', $detectable), true);
            
            // If language is not enabled and not detectable, return 404 to prevent unauthorized translation
            if (!$isEnabled && !$isDetectable) {
                global $wp_query;
                $wp_query->set_404();
                status_header(404);
                nocache_headers();
                return;
            }
            
            // SECURITY: Prevent DOS attack by blocking language/slug mismatches.
            // Only flag real non-Latin *scripts* (Cyrillic/Greek/Arabic/Hebrew/CJK/…),
            // never Latin Extended (Maltese ħ, French é, etc.). The old
            // [\x{0080}-\x{FFFF}] + incomplete accent-lang whitelist falsely 404'd
            // /mt/…ħ…/ → AI_404_Recovery self-redirect loop (curl: max redirects).
            $pathWithoutLang = preg_replace('#^/([a-z]{2})/#i', '/', $reqPath);
            if ($pathWithoutLang !== $reqPath) {
                $decodedPath = rawurldecode((string) $pathWithoutLang);
                // Scripts matching AI_Lang::non_latin_codes(): el, Cyrillic family,
                // he, ar, hi, th, ka, ja kana, CJK, ko Hangul.
                $hasNonLatinScript = (bool) preg_match(
                    '/[\x{0370}-\x{03FF}\x{0400}-\x{052F}\x{0590}-\x{05FF}\x{0600}-\x{06FF}\x{0900}-\x{097F}\x{0E00}-\x{0E7F}\x{10A0}-\x{10FF}\x{3040}-\x{30FF}\x{4E00}-\x{9FFF}\x{AC00}-\x{D7AF}]/u',
                    $decodedPath
                );

                if ($hasNonLatinScript && !\AITranslate\AI_Lang::is_non_latin($langLower)) {
                    global $wp_query;
                    $wp_query->set_404();
                    status_header(404);
                    nocache_headers();
                    return;
                }
            }
        }
    }

    // RULE 0: Strip explicit ?lang= query parameter from URL → redirect to clean path-based URL
    // The ?lang= parameter is only used internally by rewrite rules, never in actual visitor URLs.
    // Examples: /es?lang=fr → /es/  |  /?lang=es → /es/  |  /?lang={default} → /
    if (isset($_GET['lang']) && trim(sanitize_text_field(wp_unslash((string) $_GET['lang']))) !== '') {
        $cleanParams = array_map(static function ($v) {
            return is_string($v) ? sanitize_text_field(wp_unslash($v)) : $v;
        }, $_GET);
        unset($cleanParams['lang']);

        $targetPath = $reqPath;
        if ($langFromUrl === null) {
            // No language in path yet — use the GET parameter to build the correct path
            $getLang = strtolower(sanitize_key((string) $_GET['lang']));
            if ($getLang !== '' && $defaultLang && strtolower($getLang) !== strtolower((string) $defaultLang)) {
                $targetPath = '/' . $getLang . '/';
            }
        }

        // Ensure trailing slash (except bare root)
        if ($targetPath !== '/' && substr($targetPath, -1) !== '/') {
            $targetPath .= '/';
        }

        $targetUrl = home_url($targetPath);
        if (!empty($cleanParams)) {
            $targetUrl = add_query_arg($cleanParams, $targetUrl);
        }

        nocache_headers();
        wp_safe_redirect(esc_url_raw($targetUrl), 301);
        exit;
    }

    $cookieLang = isset($_COOKIE['ai_translate_lang']) ? strtolower(sanitize_key((string) $_COOKIE['ai_translate_lang'])) : '';

    // Ensure search requests have language-prefixed URL (before RULE 4 to prevent early return)
    // Check for search parameter 's' in query string
    $hasSearchParam = isset($_GET['s']) && trim(sanitize_text_field(wp_unslash((string) $_GET['s']))) !== '';
    if ($hasSearchParam) {
        // Use cookie language if available, otherwise use URL language, otherwise default
        $searchLang = $cookieLang !== '' ? $cookieLang : ($langFromUrl !== null ? $langFromUrl : (string) $defaultLang);
        if ($searchLang !== '' && $defaultLang && strtolower($searchLang) !== strtolower((string) $defaultLang)) {
            $reqUriRaw = esc_url_raw(wp_unslash((string) ($_SERVER['REQUEST_URI'] ?? '')));
            // URL decode only if double-encoded (contains %25 indicating double encoding)
            if (strpos($reqUriRaw, '%25') !== false) {
                $reqUriRaw = urldecode($reqUriRaw);
            }
            $pathNow = ai_translate_strip_site_path((string) wp_parse_url($reqUriRaw, PHP_URL_PATH));
            if ($pathNow === '' || $pathNow === '/' || !preg_match('#^/([a-z]{2})(?:/|$)#i', $pathNow)) {
                $base = home_url('/' . $searchLang . '/');
                $target = add_query_arg($_GET, $base);
                nocache_headers();
                wp_safe_redirect($target, 302);
                exit;
            }
        }
    }

    // RULE 3: Canonicalize default language - strip /{default}/ prefix, keep the rest.
    // /{default}/ → /  and  /{default}/product/x/ → /product/x/
    // (Previously always redirected to /, which broke deep default-language URLs
    // and could bounce against WooCommerce/CPT canonical redirects.)
    if ($langFromUrl !== null && $defaultLang && strtolower($langFromUrl) === strtolower((string) $defaultLang)) {
        if ($reqPath !== '/') {
            \AITranslate\AI_Lang::set_cookie((string) $defaultLang);
            \AITranslate\AI_Lang::set_current((string) $defaultLang);
            $stripped = preg_replace('#^/' . preg_quote($langFromUrl, '#') . '(?=/|$)#i', '', $reqPath);
            if (!is_string($stripped) || $stripped === '') {
                $stripped = '/';
            }
            if ($stripped !== '/' && substr($stripped, -1) !== '/') {
                $stripped .= '/';
            }
            nocache_headers();
            wp_safe_redirect(home_url($stripped), 302);
            exit;
        }
    }

    // RULE 4: If cookie exists and on root, redirect to cookie language or serve default
    if ($reqPath === '/' && $cookieLang !== '' && !$hasSearchParam) {
        if ($defaultLang && strtolower($cookieLang) !== strtolower((string) $defaultLang)) {
            // Returning visitor with non-default language preference - redirect to their preferred URL
            nocache_headers();
            ai_translate_add_vary_headers();
            wp_safe_redirect(home_url('/' . $cookieLang . '/'), 302);
            exit;
        }
        // Cookie is set to default language - serve default language page
        $finalLang = (string) $defaultLang;
        \AITranslate\AI_Lang::set_current($finalLang);
        add_filter('locale', function ($locale) {
            $currentLang = \AITranslate\AI_Lang::current();
            if ($currentLang) {
                return strtolower($currentLang) . '_' . strtoupper($currentLang);
            }
            return $locale;
        });
        \AITranslate\AI_OB::instance()->start();
        return;
    }

    // RULE 5: Non-root pages without language prefix - redirect to cookie language URL
    // If visitor has a non-default language preference and visits a page without a language
    // prefix, redirect them to the language-prefixed version so they see it in their language.
    if ($langFromUrl === null && $reqPath !== '/' && $cookieLang !== '' && $defaultLang &&
        strtolower($cookieLang) !== strtolower((string) $defaultLang) && !$hasSearchParam) {
        nocache_headers();
        ai_translate_add_vary_headers();
        wp_safe_redirect(home_url('/' . $cookieLang . $reqPath), 302);
        exit;
    }

    $resolvedLang = null;

    // RULE 1: First visit (no cookie) - detect browser language and redirect
    if ($cookieLang === '' && $langFromUrl === null && !$hasSearchParam) {
        // Crawlers must never follow a browser-language redirect: their Accept-Language
        // header is often generic/absent, and they should consistently see the default
        // language for SEO/indexing consistency.
        if (ai_translate_is_known_bot_ua()) {
            $resolvedLang = (string) $defaultLang;
        } else {
            \AITranslate\AI_Lang::reset();
            \AITranslate\AI_Lang::detect();
            $detected = \AITranslate\AI_Lang::current();
            if (!$detected) {
                $detected = (string) $defaultLang;
            }

            $resolvedLang = $detected;

            // Set cookie (central helper handles domains/headers)
            \AITranslate\AI_Lang::set_cookie($detected);

            // Redirect to language URL if not default
            // IMPORTANT: prevent browsers/proxies from caching this 302 (incognito can get "stuck").
            // Vary is defense-in-depth: a shared cache that ignores Cache-Control but honors Vary
            // will still not reuse this visitor's redirect for a visitor with a different
            // Accept-Language/cookie state.
            if ($detected && strtolower($detected) !== strtolower((string) $defaultLang)) {
                nocache_headers();
                ai_translate_add_vary_headers();
